export function translateCategory(name, t) {
  const labels = {
    "Beauté": t.categoryBeauty,
    Informatique: t.categoryIT,
    Maison: t.categoryHome,
    Transport: t.categoryTransport,
    Restauration: t.categoryFood,
  };
  return labels[name] || name;
}

export function getCurrentLanguage() {
  if (typeof window === "undefined") return "fr";
  return localStorage.getItem("app-language") || "fr";
}

export function setCurrentLanguage(locale) {
  if (typeof window === "undefined") return;
  localStorage.setItem("app-language", locale);
  window.dispatchEvent(new Event("app-language-change"));
}
